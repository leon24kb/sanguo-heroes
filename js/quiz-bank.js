    getQuestions(heroName, stage) {
        const hero = this.questions[heroName];
        // 兼容数字参数(1/2/3)和字符串参数('stage1'/'stage2'/'stage3')
        const stageKey = typeof stage === 'number' ? `stage${stage}` : stage;
        if (!hero || !hero[stageKey]) return [];
        return hero[stageKey];
    },

    getTotalQuestions(heroName) {
        const hero = this.questions[heroName];
        if (!hero) return 0;
        return (hero.stage1?.length || 0) + (hero.stage2?.length || 0) + (hero.stage3?.length || 0);
    },

    getAllQuestions() {
        const all = [];
        Object.keys(this.questions).forEach(name => {
            ['stage1', 'stage2', 'stage3'].forEach(stage => {
                (this.questions[name][stage] || []).forEach(q => {
                    all.push({ hero: name, stage, ...q });
                });
            });
        });
        return all;
    },

    getRandomQuestion(heroName, stage) {
        const qs = this.getQuestions(heroName, stage);
        if (qs.length === 0) return null;
        return qs[Math.floor(Math.random() * qs.length)];
    },

    shuffle(arr) {
        const a = [...arr];
        for (let i = a.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [a[i], a[j]] = [a[j], a[i]];
        }
        return a;
    }
